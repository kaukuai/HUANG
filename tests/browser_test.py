"""Phone interaction, private import, time preview and offline behavior in Chromium."""
from pathlib import Path
from datetime import datetime,timezone
import json
from playwright.sync_api import sync_playwright,expect

ROOT=Path(__file__).resolve().parents[1]
P=Path('/workspace/spain-planning')
report=json.loads((P/'review/app-build-report.json').read_text())
screens=P/'app-preview';screens.mkdir(exist_ok=True)
errors=[];checks=[]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True,timezone_id='Asia/Taipei')
    page=context.new_page();page.on('pageerror',lambda error:errors.append(str(error)))
    page.clock.install(time=datetime(2026,10,15,4,0,tzinfo=timezone.utc))
    page.goto('http://127.0.0.1:4173/',wait_until='networkidle')
    expect(page.locator('h1')).to_contain_text('下一站')
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.wait_for_function('navigator.serviceWorker.controller !== null')
    page.screenshot(path=str(screens/'01-mobile-home.png'))
    checks.append('分享版首頁、手機排版與離線頁面安裝成功')
    public=page.request.get('http://127.0.0.1:4173/data/share.json').text()
    for private in ['drive.google.com','Calle del Arenal','Plaza Aviador','booking-evidence']:
        assert private not in public
    assert page.request.get('http://127.0.0.1:4173/'+Path(report['private_pack']).name).status==404
    checks.append('網站不提供私人票券或住宿地址；私人包不在網站目錄')
    page.locator('.nav-item[data-tab="tickets"]').click()
    expect(page.locator('.empty-state')).to_contain_text('同行者專屬')
    page.locator('#pack-input').set_input_files(report['private_pack'])
    expect(page.locator('#toast')).to_contain_text('匯入完成',timeout=60000)
    expect(page.locator('.mode-pill')).to_contain_text('同行完整版')
    checks.append('同行包完整匯入並儲存43份附件／地圖')
    page.locator('.nav-item[data-tab="trip"]').click()
    page.locator('[data-action="preview"][data-time="2026-12-26T21:39:00+01:00"]').click()
    expect(page.locator('.focus-card h2')).to_contain_text('下車取箱')
    expect(page.locator('.next-card h2')).to_contain_text('EnjoySevilla')
    expect(page.locator('.notice')).to_contain_text('51')
    page.clock.fast_forward(5000)
    page.locator('#toast').evaluate("el => el.style.display='none'")
    page.screenshot(path=str(screens/'02-mobile-now.png'))
    checks.append('21:39準確切換為下車接車，保留先入住與51分鐘晚餐提醒')
    page.locator('.nav-item[data-tab="plan"]').click()
    page.locator('[data-action="day"][data-date="2026-12-24"]').click()
    expect(page.locator('.timeline-event')).to_have_count(17)
    expect(page.locator('.timeline')).to_contain_text('聖米格爾市場')
    page.screenshot(path=str(screens/'03-mobile-itinerary.png'))
    page.locator('.day-heading [data-action="asset"]').click()
    expect(page.locator('#viewer img')).to_be_visible()
    page.locator('#close-viewer').click()
    checks.append('12/24完整17段行程與離線路線圖可開啟')
    page.locator('.nav-item[data-tab="tickets"]').click()
    page.locator('#ticket-search').fill('地下教堂')
    expect(page.locator('.ticket-card')).to_have_count(1)
    expect(page.locator('.ticket-card .badge')).to_contain_text('日期待改訂')
    page.screenshot(path=str(screens/'04-mobile-tickets.png'))
    page.locator('#ticket-search').fill('K17')
    expect(page.locator('.ticket-card')).to_contain_text('€100.75')
    expect(page.locator('.ticket-card .badge')).to_contain_text('原票待補')
    assert page.locator('.ticket-card .file-button').count()==0
    checks.append('地下教堂日期錯誤及高鐵已購但原票未附的狀態正確')
    context.set_offline(True)
    page.reload(wait_until='networkidle')
    expect(page.locator('.mode-pill')).to_contain_text('同行完整版')
    page.locator('.nav-item[data-tab="tickets"]').click()
    page.locator('#ticket-search').fill('K01')
    page.locator('.ticket-card summary').click()
    page.locator('.ticket-card [data-action="asset"]').first.click()
    expect(page.locator('#viewer iframe')).to_be_visible()
    assert page.locator('#viewer iframe').get_attribute('src').startswith('blob:')
    page.locator('#close-viewer').click()
    page.locator('.nav-item[data-tab="plan"]').click()
    page.locator('[data-action="day"][data-date="2027-01-02"]').click()
    page.locator('.day-heading [data-action="asset"]').click()
    expect(page.locator('#viewer img')).to_be_visible()
    page.locator('#close-viewer').click()
    checks.append('飛航模式重開頁面後，行程、PDF票券、1/2地圖仍可使用')
    page.locator('.nav-item[data-tab="trip"]').click()
    page.locator('[data-action="mode"]').click()
    expect(page.locator('.mode-pill')).to_contain_text('分享行程版')
    page.locator('.nav-item[data-tab="tickets"]').click()
    expect(page.locator('.empty-state')).to_contain_text('同行者專屬')
    checks.append('可切回分享版，票券與住宿詳細資料不顯示')
    context.set_offline(False)
    for width in [320,768,1280]:
        page.set_viewport_size({'width':width,'height':900})
        page.locator('.nav-item[data-tab="plan"]').click()
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),width
    checks.append('320、390、768與1280像素畫面無整頁水平溢出')
    browser.close()
assert not errors,errors
result={'checks':checks,'browser_errors':errors,'screenshots':str(screens),'browser':'Chromium / Playwright','ios_safari':'未在實機驗證'}
(P/'review/app-browser-validation.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
print(json.dumps(result,ensure_ascii=False,indent=2))
